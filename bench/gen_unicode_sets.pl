#!/usr/bin/env perl
#
# Writes unicode_sets.h, the Unicode property sets the benchmark runs on,
# from the Unicode Character Database that ships with perl.
#
#   perl gen_unicode_sets.pl > unicode_sets.h
#
# The Unicode version is the one of the perl that runs the script.
#
use strict;
use warnings;
use Unicode::UCD qw(prop_invlist charscripts);

# General categories and binary properties, by the name the benchmark uses.
my @properties = qw(
  L Lu Ll Nd Mn P
  Alphabetic White_Space Grapheme_Extend
);

my @scripts = sort keys %{ charscripts() };

# prop_invlist returns an inversion list: codepoints at which membership
# flips, starting with "in".  Taken in pairs that is the [lo, hi) form; a
# set that runs to the last codepoint is missing its final hi.
sub intervals {
  my ($property) = @_;
  my @list = prop_invlist($property);
  die "unknown property: $property\n" if !@list && !defined prop_invlist($property);
  push @list, 0x110000 if @list % 2;
  return @list;
}

sub emit {
  my ($name, @list) = @_;
  printf "static const uint32_t unicode_set_%s[] = {", $name;
  for my $i (0 .. $#list) {
    print "\n " if $i % 8 == 0;
    printf " 0x%04X,", $list[$i];
  }
  print "\n};\n\n";
}

my $version = Unicode::UCD::UnicodeVersion();

print <<"END";
/*
 * unicode_sets.h -- Unicode property sets for the benchmark.
 *
 * Generated by gen_unicode_sets.pl from the Unicode Character Database,
 * version $version.  Do not edit.
 *
 * Each set is a canonical array of [lo, hi) intervals.
 *
 * The data is derived from the Unicode Character Database,
 * Copyright (c) Unicode, Inc., and is used under the Unicode License:
 * <https://www.unicode.org/license.txt>
 */
#ifndef UNICODE_SETS_H
#define UNICODE_SETS_H
#include <stddef.h>
#include <stdint.h>

#define UNICODE_SETS_VERSION "$version"

typedef struct {
  const char* name;
  const uint32_t* set;
  size_t count;  // in intervals
} unicode_set_t;

END

my (@property_rows, @script_rows);

for my $property (@properties) {
  my @list = intervals($property);
  emit($property, @list);
  push @property_rows, [ $property, $property, @list / 2 ];
}

for my $script (@scripts) {
  my @list = intervals("Script=$script");
  emit("sc_$script", @list);
  push @script_rows, [ $script, "sc_$script", @list / 2 ];
}

sub table {
  my ($name, @rows) = @_;
  print "static const unicode_set_t ${name}[] = {\n";
  printf "  {\"%s\", unicode_set_%s, %d},\n", @$_ for @rows;
  print "};\n\n";
  printf "#define %s_COUNT %d\n\n", uc $name, scalar @rows;
}

print "// General categories and binary properties.\n";
table('unicode_properties', @property_rows);

print "// Every script.  No two of them share a codepoint.\n";
table('unicode_scripts', @script_rows);

print "#endif /* UNICODE_SETS_H */\n";
